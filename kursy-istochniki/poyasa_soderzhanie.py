def P(*abzacy):
    return ''.join('<p>' + a + '</p>' for a in abzacy)


def UL(*punkty):
    return '<ul>' + ''.join('<li>' + p + '</li>' for p in punkty) + '</ul>'


def H(t):
    return '<h3>' + t + '</h3>'


def TAB(shapka, stroki):
    h = ''.join('<th>' + x + '</th>' for x in shapka)
    r = ''.join('<tr>' + ''.join('<td>' + x + '</td>' for x in s) + '</tr>' for s in stroki)
    return '<div class="scroller"><table><thead><tr>' + h + '</tr></thead><tbody>' + r + '</tbody></table></div>'


def KEIS(situaciya, razbor):
    return ('<div class="keis"><span class="tag">Кейс</span><p>' + situaciya + '</p>'
            '<details><summary>Разбор</summary><p>' + razbor + '</p></details></div>')


def NELZYA(t):
    return '<div class="pitfall"><span class="tag">Так делать нельзя</span><p>' + t + '</p></div>'


def VAZHNO(t):
    return '<div class="robot"><span class="tag">Главное</span><p>' + t + '</p></div>'


SHAGI = []


def shag(rail, title, html, q, opts, right, why):
    SHAGI.append({'rail': rail, 'title': title, 'html': html,
                  'check': {'q': q, 'opts': opts, 'right': right, 'why': why}})


