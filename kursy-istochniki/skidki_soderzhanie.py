# Знак % не отрывать от числа на телефоне: неразрывный пробел перед % во всех текстах.
def _nbsp(x):
    if isinstance(x, str):
        return x.replace(' %', ' %')
    if isinstance(x, list):
        return [_nbsp(i) for i in x]
    if isinstance(x, dict):
        return {k: _nbsp(v) for k, v in x.items()}
    return x


