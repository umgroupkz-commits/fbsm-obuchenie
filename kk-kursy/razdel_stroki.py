def kursy():
    t = io.open(os.path.join(FUN, 'kursy.ts'), encoding='utf-8').read()
    t = re.sub(r'^\s*//.*$', '', t, flags=re.M)
    t = t[t.index('['):t.rindex(']') + 1]
    return json.loads(t)


def changelog():
    t = io.open(os.path.join(FUN, 'index.ts'), encoding='utf-8').read()
    blok = t[t.index('const CHANGELOG_OB'):]
    blok = blok[:blok.index('\n];')]
    return [json.loads(m.group(0)) for m in re.finditer(r'"(?:[^"\\\n]|\\.)*"', blok) if not re.match(r'"\d{4}-\d\d-\d\d"', m.group(0))]


def vse():
    out = list(STRANICY)
    for k in kursy():
        for pole in ('title', 'short', 'about', 'who'):
            if k.get(pole):
                out.append(k[pole])
                if pole == 'who':          # «≈ 15 минут · Продавцы» — who подставляется в шаблон отдельно
                    out += [x.strip() for x in k[pole].split(',')]
    out += changelog()
    return list(dict.fromkeys(norm(x) for x in out if re.search('[А-Яа-яЁё]', x)))


